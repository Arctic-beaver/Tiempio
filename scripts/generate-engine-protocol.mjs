import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { requireLifecycleOwnership } from './lifecycle/ownership-guard.mjs'

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const schemaPath = resolve(repositoryRoot, 'packages/contracts/schema/engine-protocol.schema.json')
const outputPaths = Object.freeze({
	typescript: resolve(
		repositoryRoot,
		'packages/contracts/src/generated/engine-protocol.generated.ts'
	),
	rust: resolve(repositoryRoot, 'engine/crates/protocol/src/generated.rs')
})

function assertPositiveInteger(value, label) {
	if (!Number.isSafeInteger(value) || value <= 0) {
		throw new Error(`${label} must be a positive safe integer.`)
	}
}

function assertStableStringList(value, label) {
	if (
		!Array.isArray(value) ||
		value.length === 0 ||
		!value.every(
			(item) => typeof item === 'string' && /^[a-z][a-z0-9]*(?:[.-][a-z0-9]+)*$/u.test(item)
		) ||
		new Set(value).size !== value.length
	) {
		throw new Error(`${label} must be a non-empty unique stable-code list.`)
	}
}

export function parseEngineProtocolSchema(source) {
	const schema = JSON.parse(source)
	assertPositiveInteger(schema.schemaVersion, 'schemaVersion')
	assertPositiveInteger(schema.engineProtocolVersion, 'engineProtocolVersion')
	for (const [name, value] of Object.entries(schema.limits ?? {})) {
		assertPositiveInteger(value, `limits.${name}`)
	}
	for (const name of [
		'maxFrameBytes',
		'maxPayloadBytes',
		'maxIdentifierBytes',
		'maxBatchItems',
		'maxJsonDepth',
		'maxEngineLayers',
		'maxTempoPoints',
		'maxMeterPoints',
		'maxMusicalEvents',
		'maxPreparedActions',
		'maxPreparedBeats',
		'maxActionsPerBlock',
		'maxVoices',
		'maxBlockFrames',
		'minSampleRate',
		'maxSampleRate',
		'maxOfflineSeconds',
		'maxPreviewEvents',
		'maxPreviewChordSize',
		'maxPreviewDurationMs'
	]) {
		if (!Object.hasOwn(schema.limits ?? {}, name)) {
			throw new Error(`limits.${name} is required.`)
		}
	}
	if (schema.limits.maxPayloadBytes >= schema.limits.maxFrameBytes) {
		throw new Error('maxPayloadBytes must be smaller than maxFrameBytes.')
	}
	assertStableStringList(schema.commands, 'commands')
	assertStableStringList(schema.events, 'events')
	assertStableStringList(schema.capabilities, 'capabilities')
	for (const profile of [
		'applicationCommonCapabilities',
		'audibleOutputCapabilities',
		'nativeHostCapabilities',
		'webWorkletCapabilities'
	]) {
		assertStableStringList(schema[profile], profile)
		for (const capability of schema[profile]) {
			if (!schema.capabilities.includes(capability)) {
				throw new Error(`${profile} contains unknown capability ${capability}.`)
			}
		}
	}
	for (const capability of schema.applicationCommonCapabilities) {
		if (!schema.nativeHostCapabilities.includes(capability)) {
			throw new Error(`nativeHostCapabilities is missing common capability ${capability}.`)
		}
		if (!schema.webWorkletCapabilities.includes(capability)) {
			throw new Error(`webWorkletCapabilities is missing common capability ${capability}.`)
		}
	}
	const nativeOutputs = schema.audibleOutputCapabilities.filter((capability) =>
		schema.nativeHostCapabilities.includes(capability)
	)
	const webOutputs = schema.audibleOutputCapabilities.filter((capability) =>
		schema.webWorkletCapabilities.includes(capability)
	)
	if (nativeOutputs.length !== 1 || webOutputs.length !== 1) {
		throw new Error('Each audible engine profile must expose exactly one output capability.')
	}
	assertStableStringList(schema.diagnosticCodes, 'diagnosticCodes')
	return Object.freeze({
		...schema,
		limits: Object.freeze({ ...schema.limits }),
		commands: Object.freeze([...schema.commands]),
		events: Object.freeze([...schema.events]),
		capabilities: Object.freeze([...schema.capabilities]),
		applicationCommonCapabilities: Object.freeze([...schema.applicationCommonCapabilities]),
		audibleOutputCapabilities: Object.freeze([...schema.audibleOutputCapabilities]),
		nativeHostCapabilities: Object.freeze([...schema.nativeHostCapabilities]),
		webWorkletCapabilities: Object.freeze([...schema.webWorkletCapabilities]),
		diagnosticCodes: Object.freeze([...schema.diagnosticCodes])
	})
}

function typescriptList(name, values) {
	const entries = values
		.map((value, index) => `\t'${value}'${index === values.length - 1 ? '' : ','}`)
		.join('\n')
	return `export const ${name} = Object.freeze([\n${entries}\n] as const)`
}

function typescriptLimits(limits) {
	const entries = Object.entries(limits)
		.map(
			([name, value], index, values) =>
				`\t${name}: ${String(value)}${index === values.length - 1 ? '' : ','}`
		)
		.join('\n')
	return `export const engineProtocolLimits = Object.freeze({\n${entries}\n} as const)`
}

export function renderTypescriptBinding(schema) {
	return [
		'// Generated by scripts/generate-engine-protocol.mjs. Do not edit directly.',
		'',
		`export const engineProtocolSchemaVersion = ${String(schema.schemaVersion)} as const`,
		`export const engineProtocolVersion = ${String(schema.engineProtocolVersion)} as const`,
		typescriptLimits(schema.limits),
		'',
		typescriptList('engineCommandTypes', schema.commands),
		'export type EngineCommandType = (typeof engineCommandTypes)[number]',
		'',
		typescriptList('engineEventTypes', schema.events),
		'export type EngineEventType = (typeof engineEventTypes)[number]',
		'',
		typescriptList('engineCapabilityCodes', schema.capabilities),
		'export type EngineCapabilityCode = (typeof engineCapabilityCodes)[number]',
		'',
		typescriptList('applicationCommonCapabilityCodes', schema.applicationCommonCapabilities),
		'',
		typescriptList('audibleOutputCapabilityCodes', schema.audibleOutputCapabilities),
		'',
		typescriptList('nativeHostCapabilityCodes', schema.nativeHostCapabilities),
		'',
		typescriptList('webWorkletCapabilityCodes', schema.webWorkletCapabilities),
		'',
		typescriptList('engineDiagnosticCodes', schema.diagnosticCodes),
		'export type EngineDiagnosticCode = (typeof engineDiagnosticCodes)[number]',
		''
	].join('\n')
}

function rustList(name, values) {
	if (values.length <= 2) {
		return `pub const ${name}: &[&str] = &[${values.map((value) => JSON.stringify(value)).join(', ')}];`
	}
	const entries = values.map((value) => `    ${JSON.stringify(value)},`).join('\n')
	return `pub const ${name}: &[&str] = &[\n${entries}\n];`
}

function rustConstantName(name) {
	return name.replaceAll(/([a-z0-9])([A-Z])/gu, '$1_$2').toUpperCase()
}

function rustInteger(value) {
	return String(value).replace(/\B(?=(\d{3})+(?!\d))/gu, '_')
}

function rustFieldName(name) {
	return name.replaceAll(/([a-z0-9])([A-Z])/gu, '$1_$2').toLowerCase()
}

function rustLimits(limits) {
	return Object.entries(limits)
		.map(
			([name, value]) =>
				`pub const ENGINE_PROTOCOL_${rustConstantName(name)}: usize = ${rustInteger(value)};`
		)
		.join('\n')
}

function rustProtocolLimits(limits) {
	const fields = Object.keys(limits)
		.map((name) => `    pub ${rustFieldName(name)}: usize,`)
		.join('\n')
	const current = Object.keys(limits)
		.map(
			(name) =>
				`            ${rustFieldName(name)}: ENGINE_PROTOCOL_${rustConstantName(name)},`
		)
		.join('\n')
	return `#[derive(Clone, Debug, serde::Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct ProtocolLimits {
${fields}
}

impl ProtocolLimits {
    #[must_use]
    pub const fn current() -> Self {
        Self {
${current}
        }
    }
}`
}

export function renderRustBinding(schema) {
	return [
		'// Generated by scripts/generate-engine-protocol.mjs. Do not edit directly.',
		'',
		`pub const ENGINE_PROTOCOL_SCHEMA_VERSION: u32 = ${String(schema.schemaVersion)};`,
		`pub const ENGINE_PROTOCOL_VERSION: u32 = ${String(schema.engineProtocolVersion)};`,
		rustLimits(schema.limits),
		'',
		rustProtocolLimits(schema.limits),
		'',
		rustList('ENGINE_COMMAND_TYPES', schema.commands),
		'',
		rustList('ENGINE_EVENT_TYPES', schema.events),
		'',
		rustList('ENGINE_CAPABILITY_CODES', schema.capabilities),
		'',
		rustList('APPLICATION_COMMON_CAPABILITY_CODES', schema.applicationCommonCapabilities),
		'',
		rustList('AUDIBLE_OUTPUT_CAPABILITY_CODES', schema.audibleOutputCapabilities),
		'',
		rustList('NATIVE_HOST_CAPABILITY_CODES', schema.nativeHostCapabilities),
		'',
		rustList('WEB_WORKLET_CAPABILITY_CODES', schema.webWorkletCapabilities),
		'',
		rustList('ENGINE_DIAGNOSTIC_CODES', schema.diagnosticCodes),
		''
	].join('\n')
}

export function expectedProtocolBindings() {
	const schema = parseEngineProtocolSchema(readFileSync(schemaPath, 'utf8'))
	return Object.freeze({
		[outputPaths.typescript]: renderTypescriptBinding(schema),
		[outputPaths.rust]: renderRustBinding(schema)
	})
}

export function updateProtocolBindings({ check = false } = {}) {
	const expected = expectedProtocolBindings()
	const stale = []
	for (const [path, contents] of Object.entries(expected)) {
		if (check) {
			let actual = null
			try {
				actual = readFileSync(path, 'utf8')
			} catch (error) {
				if (error?.code !== 'ENOENT') throw error
			}
			if (actual !== contents) stale.push(path)
			continue
		}
		mkdirSync(dirname(path), { recursive: true })
		writeFileSync(path, contents, 'utf8')
	}
	if (stale.length > 0) {
		throw new Error(
			`Generated engine protocol bindings are stale: ${stale.join(', ')}. Run npm run generate:protocol.`
		)
	}
	const message = check
		? 'PASS generated engine protocol bindings are current.'
		: 'PASS generated engine protocol bindings updated deterministically.'
	console.log(message)
	return message
}

const invoked = process.argv[1] === undefined ? null : pathToFileURL(resolve(process.argv[1])).href
if (invoked === import.meta.url) {
	requireLifecycleOwnership('Engine protocol generation')
	updateProtocolBindings({ check: process.argv.includes('--check') })
}
